"""CDLI composite ATF (with #tr.ts normalization and #tr.en translation lines) -> Markdown, optionally aligned with
one witness ATF (e.g. a stele or tablet exemplar), and a JSON-lines data file for translators.

usage:
    python3 -I tools/cdli_composite2md.py <composite.atf> <out.md> <title> <url> [--witness <witness.atf> <siglum>] [--jsonl <out.jsonl>]

Get the ATF from the CDLI JSON export (the per-artifact ".atf" URL fails):
    curl -sL --max-time 60 -A 'Mozilla/5.0' -o P464358.json https://cdli.earth/artifacts/464358/json
    python3 -I -c "import json;d=json.load(open('P464358.json'))[0];open('P464358.atf','w').write(d['inscription']['atf'])"
  The composite's JSON also embeds the witnesses' ATF (d['witnesses'][i]['witness']['inscription']['atf']) when CDLI has it.

What it does:
  - keeps the composite's structure lines (@prologue, @law N, @epilogue, $ …, # comments) as headings / notes;
  - each text line -> "**<n>** `<transliteration>`" + "ts: <normalization>" + "en: <CDLI English>";
  - with --witness: aligns the witness's lines to the composite by the transliteration sequence (difflib), and prints
    the witness reference ("stele obv. 3:12" = surface, column, line) and, when the witness's transliteration differs
    after normalising spaces/brackets, the witness's own line;
  - --jsonl: one JSON object per composite line: {n, section, atf, ts, en, wit_ref, wit_atf}.
Written 2026-10-17 for the Laws of Hammurabi (CDLI P464358 composite + the Louvre stele P249253).
"""
import sys, re, json, difflib


def parse_composite(fn):
    lines = []; section = None; cur = None; notes = []
    for raw in open(fn, encoding='utf-8'):
        l = raw.rstrip('\r\n')
        if l.startswith('@prologue') or l.startswith('@epilogue') or l.startswith('@law'):
            section = l[1:].strip(); continue
        m = re.match(r"^(\d+'?)\.\s*(.*)$", l)
        if m:
            cur = {'n': m.group(1), 'section': section, 'atf': m.group(2).strip(), 'ts': '', 'en': '', 'notes': list(notes)}
            notes = []; lines.append(cur); continue
        if l.startswith('#tr.ts:') and cur:
            cur['ts'] = l[7:].strip(); continue
        if l.startswith('#tr.en:') and cur:
            cur['en'] = l[7:].strip(); continue
        if l.startswith('$') or (l.startswith('#') and not l.startswith('#atf') and not l.startswith('#tr')):
            if cur and l.startswith('#'):
                cur['notes'].append(l)
            else:
                notes.append(l)
    return lines


def parse_witness(fn):
    out = []; surf = 'obv.'; col = None
    for raw in open(fn, encoding='utf-8'):
        l = raw.rstrip('\r\n')
        if l.startswith('@reverse'):
            surf = 'rev.'; continue
        if l.startswith('@obverse'):
            surf = 'obv.'; continue
        m = re.match(r'@column (\S+)', l)
        if m:
            col = m.group(1); continue
        m = re.match(r"^(\d+'?)\.\s*(.*)$", l)
        if m:
            out.append({'ref': f'{surf} {col}:{m.group(1)}', 'atf': m.group(2).strip()})
    return out


def key(s):
    s = re.sub(r'[\[\]#!?<>⸢⸣]', '', s)
    s = re.sub(r'\s+', ' ', s).strip()
    return s


def main():
    a = sys.argv[1:]
    wit = None; jsonl = None
    if '--witness' in a:
        i = a.index('--witness'); wit = (a[i + 1], a[i + 2]); del a[i:i + 3]
    if '--jsonl' in a:
        i = a.index('--jsonl'); jsonl = a[i + 1]; del a[i:i + 2]
    comp, out, title, url = a[:4]
    L = parse_composite(comp)
    if wit:
        W = parse_witness(wit[0])
        sm = difflib.SequenceMatcher(None, [key(x['atf']) for x in L], [key(x['atf']) for x in W], autojunk=False)
        for tag, i1, i2, j1, j2 in sm.get_opcodes():
            if tag in ('equal', 'replace') and (i2 - i1) == (j2 - j1):
                for k in range(i2 - i1):
                    L[i1 + k]['wit_ref'] = W[j1 + k]['ref']
                    if key(L[i1 + k]['atf']) != key(W[j1 + k]['atf']) or L[i1 + k]['atf'] != W[j1 + k]['atf']:
                        L[i1 + k]['wit_atf'] = W[j1 + k]['atf']
    o = [f'# {title}', '', f'Source: {url}. Generated by `tools/cdli_composite2md.py` from the CDLI ATF (composite).']
    if wit:
        o.append(f'Aligned with the witness `{wit[1]}` ({wit[0].split("/")[-1]}): its reference is given as "surface column:line"; '
                 'its own transliteration is printed (`{0}:`) where it differs from the composite.'.format(wit[1]))
    o += ['', 'Format: `**<composite line>**` transliteration; `ts:` CDLI normalization; `en:` CDLI English (translator not named in the ATF).', '']
    sec = None
    for x in L:
        if x['section'] != sec:
            sec = x['section']; o += ['', f'## {sec}', '']
        for n in x['notes']:
            if n.startswith('$'):
                o.append(f'_{n}_  ')
        ref = f" ({wit[1]} {x['wit_ref']})" if x.get('wit_ref') else (f' ({wit[1]}: –)' if wit else '')
        o.append(f"**{x['n']}**{ref} `{x['atf']}`  ")
        if x.get('wit_atf'):
            o.append(f"  {wit[1]}: `{x['wit_atf']}`  ")
        o.append(f"  ts: {x['ts']}  ")
        o.append(f"  en: {x['en']}  ")
        for n in x['notes']:
            if n.startswith('#'):
                o.append(f'  note: {n[1:].strip()}  ')
    open(out, 'w', encoding='utf-8').write('\n'.join(o) + '\n')
    if jsonl:
        with open(jsonl, 'w', encoding='utf-8') as f:
            for x in L:
                f.write(json.dumps({k: x.get(k, '') for k in ('n', 'section', 'atf', 'ts', 'en', 'wit_ref', 'wit_atf', 'notes')},
                                   ensure_ascii=False) + '\n')
    print('lines', len(L), 'aligned', sum(1 for x in L if x.get('wit_ref')), 'witness differs', sum(1 for x in L if x.get('wit_atf')))


main()
