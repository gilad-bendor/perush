#!/usr/bin/env python3
"""
Re-obtain the git-ignored source files (sources/), e.g. in a fresh clone or a Claude Cloud session.

The repository is public, so most raw sources are git-ignored (guidelines §8): only their README.md files are
committed. This tool keeps a manifest of every ignored file - how to re-obtain it and its checksum - and restores
whatever is missing.

    python3 -I tools/sources_sync.py status   [--all]                 what is missing, per item
    python3 -I tools/sources_sync.py fetch    [--all] [--only REGEX] [--dest DIR] [--dry-run] [--jobs N]
    python3 -I tools/sources_sync.py verify   [--all]                 compare the files that are there with the manifest
    python3 -I tools/sources_sync.py snapshot                         (where the files are) rewrite the manifest

  --all      include the "archive" tier (old page scans, photos, PDFs of studies: ~400 MB, not needed for the
             translation work). Without it, only the "work" tier (what the tools and the translators read).
  --only     restrict to items whose id (a path under sources/) matches the regex.
  --dest     restore into another folder (a stand-in for sources/; for testing). Default: sources/.
  --jobs     items fetched in parallel (default 4).

Files:
  sources/fetch-recipes.tsv   hand-written: how to re-obtain the items that the built-in rules don't cover.
  sources/MANIFEST.json       generated by "snapshot": every ignored file, its item, size and sha256.

After a fetch, every restored file is compared with the manifest's checksum:
  ok        identical to the copy the translations were made from (dates in "generated/retrieved" stamps ignored);
  page      a saved web page whose markup differs (menus, tokens): expected, not reported one by one;
  regen     a file our tools make from a raw download (eBL reading editions, SEAL and fragment extractions) that the
            current tool version writes differently, while the raw data is the same: not reported one by one;
  CHANGED   the source has changed since (eBL and ORACC are living editions): the file is kept - check what changed
            before relying on it (the old copy is gone; the manifest date says when ours was taken);
  FAILED    not restored: the reason is printed (a host blocked by the cloud allowlist, a missing tool, a page that
            needs a browser...). Items of kind "manual"/"adhoc" are never fetched: their note says what to do.

A host that the cloud network allowlist blocks shows as "blocked by the network allowlist": add it to the cloud
environment's allowed domains (claude.ai UI) - and to ../domains.txt if it is new.

Never executes anything downloaded. ETCSL's zip ships Windows .exe/.dll files: they are not extracted.
"""

